let a = 10;
let b = 5;

// 1. Equal to (==)
console.log("a == b:", a == b);

// 2. Strictly equal to (===)
console.log("a === b:", a === b);

// 3. Not equal to (!=)
console.log("a != b:", a != b);

// 4. Strictly not equal to (!==)
console.log("a !== b:", a !== b);

// 5. Greater than (>)
console.log("a > b:", a > b);

// 6. Less than (<)
console.log("a < b:", a < b);

// 7. Greater than or equal to (>=)
console.log("a >= b:", a >= b);

// 8. Less than or equal to (<=)
console.log("a <= b:", a <= b);